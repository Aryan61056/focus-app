#!/usr/bin/env python3
"""Generate mac/Sources/FocusJudge/PromptText.swift from core/prompts/*.txt.

  python3 tools/sync_prompts.py          # write the file
  python3 tools/sync_prompts.py --check  # exit 1 if it is out of date (used by the eval tests)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "mac", "Sources", "FocusJudge", "PromptText.swift")


def render() -> str:
    parts = ["// Generated by tools/sync_prompts.py from core/prompts. Do not edit by hand.\n\npublic enum PromptText {\n"]
    for name, ident in (("instructions_v1.txt", "instructionsV1"), ("instructions_v2.txt", "instructionsV2")):
        with open(os.path.join(ROOT, "core", "prompts", name), encoding="utf-8") as fh:
            text = fh.read()
        assert '"""#' not in text
        parts.append('    public static let %s = #"""\n%s\n"""#\n' % (ident, text))
    parts.append("}\n")
    return "\n".join(parts)


if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        sys.exit(0 if old == new else 1)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(new)
    print("wrote", OUT)
